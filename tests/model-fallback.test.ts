import assert from "assert";
import {
  isModelAvailable,
  recordModelFailure,
  recordModelSuccess,
} from "../lib/ai/circuit-breaker";

async function runModelFallbackTest() {
  console.log("==================================================================");
  console.log("🔄 Running Model Chain Fallback & Circuit Breaker Test");
  console.log("==================================================================\n");

  const primaryModel = `mock-primary-model-${Date.now()}`;
  const fallbackModel = `mock-fallback-model-${Date.now()}`;
  const modelChain = [primaryModel, fallbackModel];

  // 1. Initial State: Both models available
  console.log("🔍 Test 1: Verifying initial model availability...");
  assert.strictEqual(isModelAvailable(primaryModel), true);
  assert.strictEqual(isModelAvailable(fallbackModel), true);
  console.log("  ✓ Both models initially available.");

  // 2. Simulate Primary Model Failure (429 Rate Limit)
  console.log("🔍 Test 2: Forcing primary model failure and tripping circuit breaker...");
  // First failure
  recordModelFailure(primaryModel, new Error("OpenRouter [429] Rate limit exceeded"));
  assert.strictEqual(isModelAvailable(primaryModel), true, "1 failure should not trip breaker yet");

  // Second failure: should trip the circuit breaker
  recordModelFailure(primaryModel, new Error("OpenRouter [429] Rate limit exceeded"));
  assert.strictEqual(isModelAvailable(primaryModel), false, "2 failures must trip breaker into cooldown");
  console.log("  ✓ Primary model tripped circuit breaker and entered cooldown.");

  // 3. Simulate fallback chain execution
  console.log("🔍 Test 3: Simulating fallback loop execution under tripped breaker...");
  let selectedModel = "";
  let answerContent = "";

  for (const model of modelChain) {
    if (!isModelAvailable(model)) {
      console.log(`    - Skipping model "${model}" (in circuit breaker cooldown).`);
      continue;
    }

    try {
      // Simulate successful fallback model response
      selectedModel = model;
      answerContent = "Grounded response successfully generated by fallback model.";
      recordModelSuccess(model);
      break;
    } catch {
      recordModelFailure(model);
    }
  }

  assert.strictEqual(
    selectedModel,
    fallbackModel,
    "Execution must seamlessly fall through to secondary model"
  );
  assert.ok(
    answerContent.includes("fallback model"),
    "Answer must be returned from fallback model"
  );
  console.log(`  ✓ Success: Request automatically arrived from fallback model: "${selectedModel}".`);

  // 4. Verify Subsequent Request Skips Primary Model Without Network Call
  console.log("🔍 Test 4: Verifying subsequent request instantly bypasses primary model...");
  const availableModelsForNextCall = modelChain.filter((m) => isModelAvailable(m));
  assert.deepStrictEqual(
    availableModelsForNextCall,
    [fallbackModel],
    "Subsequent calls must only include healthy fallback models"
  );
  console.log("  ✓ Circuit breaker cleanly skipped failing primary model on subsequent turn.");

  console.log("\n==================================================================");
  console.log("✅ ALL MODEL FALLBACK & CIRCUIT BREAKER TESTS PASSED!");
  console.log("==================================================================");
}

runModelFallbackTest().catch((err) => {
  console.error("❌ Model fallback test failed:", err);
  process.exit(1);
});

